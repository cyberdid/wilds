# Kodo: a huge hunched beast two tiles long. Slate-grey hide, a high back armoured with
# brown plates fringed with shaggy hair, a low heavy head with a great curved nose horn,
# pillar legs on broad toed feet and a thick tapering tail. Built from shaded forms so all
# frames share one body.
# ==========================================================================================


def _ell(cx: float, cy: float, rx: float, ry: float, w: int = 32, h: int = 24) -> set:
    return {(x, y) for y in range(h) for x in range(w)
            if ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2 <= 1.0}


def _shade(c: Canvas, pts: set, light: str, main: str, dark: str, deep: str = "") -> None:
    """Fill a form lit from the top-left: rim light on top/left, shadow on bottom/right."""
    for (x, y) in pts:
        if (x, y - 1) not in pts or (x - 1, y) not in pts and (x, y - 2) not in pts:
            ch = light
        elif (x, y + 1) not in pts or (x + 1, y) not in pts:
            ch = dark
        elif deep and (x, y + 2) not in pts:
            ch = dark
        else:
            ch = main
        c.set(x, y, ch)


def _kodo(dy: int = 0, head_dy: int = 0, fore: tuple[int, int] = (0, 0), hind: tuple[int, int] = (0, 0),
          lift: tuple[int, int, int, int] = (0, 0, 0, 0), dead: bool = False) -> Grid:
    """``fore``/``hind`` = (near, far) foot offsets; ``lift`` raises (near fore, far fore,
    near hind, far hind) feet off the ground."""
    c = Canvas(32, 24)
    g = 22  # ground row (the outline goes below it)
    by = dy + (4 if dead else 0)
    if not dead:
        # far legs (dark), then near legs: thick pillars on broad feet with pale toenails
        for x0, off, up in ((18, fore[1], lift[1]), (9, hind[1], lift[3])):
            leg = {(x0 + k + (off if y > 18 else 0), y) for y in range(14 + dy, g + 1 - up)
                   for k in range(3)}
            _shade(c, leg, "2", "1", "0")
            for k in range(3):
                c.set(x0 + k + off, g - up, "0")
        for x0, off, up in ((21, fore[0], lift[0]), (5, hind[0], lift[2])):
            leg = {(x0 + k + (off if y > 18 else 0), y) for y in range(14 + dy, g + 1 - up)
                   for k in range(4)}
            _shade(c, leg, "3", "2", "1")
            for k in range(4):
                c.set(x0 + k + off, g - up, "n" if k % 2 == 0 else "1")
    else:
        # collapsed: legs folded out from under the belly, front and back
        for pts, ch in ((((22, 18), (26, 21), (27, 22)), "2"), (((6, 18), (3, 21), (2, 22)), "2")):
            for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
                c.line(x0, y0, x1, y1, ch)
                c.line(x0 + 1, y0, x1 + 1, y1, ch)
    # tail, body barrel and the hump over the shoulders
    tail = {(x, y) for x in range(0, 6) for y in range(10 + by, 18 + by)
            if abs((y - 10 - by) - (6 - x) * 1.1) < 1.3 + (x - 1) * 0.25 and y - by < 18 - x // 3}
    _shade(c, tail, "3", "2", "1")
    body = _ell(14.5, 12.5 + by, 11.5, 5.6) | _ell(14.0, 9.5 + by, 8.5, 5.5) | _ell(20.0, 10.5 + by, 5.0, 4.0)
    body = {(x, y) for (x, y) in body if y <= g}
    _shade(c, body, "4", "3", "2", deep="1")
    for (x, y) in body:  # belly shade band
        if (x, y + 1) in body and (x, y + 2) not in body and y > 13 + by:
            c.set(x, y, "1")
    # armoured back: rows of staggered brown plates, dark seams, a shaggy fringe below
    top: dict[int, int] = {}
    for (x, y) in body:
        top[x] = min(top.get(x, 99), y)
    for (x, y) in body:
        depth = y - top[x]
        edge = 5 + ((x * 7) % 3 == 0) - (x < 7) - (x > 22) - (x < 5)
        if depth < edge:
            row = depth // 2
            col = (x + row * 2) % 4
            if depth % 2 == 1:
                ch = "P" if col in (0, 3) else "p"
            elif col == 0:
                ch = "P"
            else:
                ch = "s" if col == 1 else "p"
            c.set(x, y, ch)
        elif depth == edge:
            c.set(x, y, "P" if x % 2 == 0 else "p")  # shaggy hair hanging from the plates
        elif depth == edge + 1 and x % 2 == 0 and 8 < x < 24:
            c.set(x, y, "P")
    # head: low and heavy, a big curved nose horn and a short brow horn
    hx, hy = 26, 14 + by + head_dy
    for (x, y) in _ell(hx - 1.5, hy + 0.5, 1.5, 3.2):   # neck shadow behind the jaw
        if (x, y) in body:
            c.set(x, y, "1")
    head = _ell(hx + 0.5, hy + 0.5, 4.0, 3.6) | _ell(hx + 3.2, hy + 1.5, 2.3, 2.1)
    _shade(c, head, "4", "3", "2")
    c.set(hx, hy - 1, "x" if dead else "e")
    c.set(hx + 4, hy + 1, "1")          # nostril
    c.set(hx + 3, hy + 3, "1")          # mouth line
    c.set(hx + 2, hy + 3, "1")
    for (x, y, ch) in ((hx + 3, hy - 1, "N"), (hx + 4, hy - 1, "n"), (hx + 4, hy - 2, "n"),
                       (hx + 5, hy - 2, "N"), (hx + 5, hy - 3, "n"), (hx + 5, hy - 4, "N"),
                       (hx + 5, hy - 5, "n"), (hx + 4, hy - 6, "N"),
                       (hx - 1, hy - 3, "n"), (hx - 2, hy - 4, "n"), (hx - 3, hy - 5, "N")):
        c.set(x, y, ch)
    return outline_grid(c.grid(), "k")


def _kodo_dead() -> Grid:
    """Rolled onto its side with its back to the viewer: the plated hump rests on the
    ground, the four pillar legs stick stiffly out over the belly, the head lies on its cheek."""
    c = Canvas(32, 24)
    a = 26.5  # the standing body mirrored top-to-bottom about y = a / 2
    for (x0, x1, lean) in ((6, 3, -1), (9, 3, -1), (19, 3, 1), (22, 3, 1)):
        pts = {(x0 + k + (lean * (11 - y)) // 3, y) for y in range(4, 12) for k in range(x1)}
        near = x0 in (6, 22)
        _shade(c, pts, "3" if near else "2", "2" if near else "1", "1" if near else "0")
        tip = min(y for _, y in pts)
        for (x, y) in pts:
            if y == tip:
                c.set(x, y, "n" if x % 2 == 0 else "1")
    tail = {(x, y) for x in range(0, 6) for y in range(16, 22) if abs((a - y - 10) - (6 - x) * 1.1) < 1.6}
    _shade(c, tail, "3", "2", "1")
    body = _ell(14.5, a - 12.5, 11.5, 5.6) | _ell(14.0, a - 9.5, 8.5, 5.5) | _ell(20.0, a - 10.5, 5.0, 4.0)
    body = {(x, y) for (x, y) in body if y <= 22}
    _shade(c, body, "4", "3", "2", deep="1")
    for (x, y) in body:  # pale belly skin, now facing up
        if (x, y - 1) not in body:
            c.set(x, y, "5")
    bottom: dict[int, int] = {}
    for (x, y) in body:
        bottom[x] = max(bottom.get(x, -1), y)
    for (x, y) in body:  # the armoured back, now along the ground
        depth = bottom[x] - y
        if depth < 4:
            col = (x + (depth // 2) * 2) % 4
            c.set(x, y, "P" if col == 0 or depth % 2 == 1 and col == 3 else ("s" if col == 1 else "p"))
        elif depth == 4:
            c.set(x, y, "P" if x % 2 == 0 else "p")
    hx, hy = 26, 18
    head = _ell(hx + 0.5, hy + 0.5, 4.0, 3.6) | _ell(hx + 3.2, hy + 1.5, 2.3, 2.1)
    _shade(c, head, "4", "3", "2")
    c.set(hx, hy - 1, "x")
    c.set(hx + 4, hy + 1, "1")
    c.set(hx + 2, hy + 3, "1")
    c.set(hx + 3, hy + 3, "1")
    for (x, y, ch) in ((hx + 3, hy - 1, "N"), (hx + 4, hy - 1, "n"), (hx + 5, hy - 2, "n"),
                       (hx + 5, hy - 3, "N"), (hx + 5, hy - 4, "n"), (hx - 1, hy - 3, "n"),
                       (hx - 2, hy - 4, "N")):
        c.set(x, y, ch)
    return _shadow(outline_grid(c.grid(), "k"), 2, 30, 22)


