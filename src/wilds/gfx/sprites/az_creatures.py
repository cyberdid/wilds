"""Azeroth / Mulgore art: creatures. Must satisfy
``wilds.azeroth.manifest.required()["creatures"]`` (see docs/azeroth/mulgore-art-manifest.md).

The beasts and critters of the plains, at real scale (1 tile = 16 px = 2 yards): critters fit
12x12, small beasts 16x16, a tallstrider stands 16x24 and a kodo is two tiles long (32x24).
Every animal faces RIGHT in a 3/4 side view with its feet (and their 1px ink outline) on the
bottom row. Families share one body: wolf/timber wolf, cougar/lion/mountain lion,
vulture/eagle. Bodies are hand-drawn fill grids; legs are posed polylines stamped under
them, so a walk cycle only moves limbs and bobs the body by 1px (no sliding); the ink
outline is added last around the whole silhouette.
"""

