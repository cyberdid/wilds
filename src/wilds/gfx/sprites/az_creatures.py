# --- helpers ------------------------------------------------------------------------------

Leg = tuple[str, tuple[tuple[int, int], ...], int, int, str]


def L(ch: str, *pts: tuple[int, int], paw: int = 1, w: int = 1, foot: str = "") -> Leg:
    """A leg: a polyline hip -> ... -> foot in colour ``ch``, ``w`` px thick (growing to the
    right); ``paw`` adds that many pixels in front of the foot (0: lifted or a hoof);
    ``foot`` recolours the last row (hooves)."""
    return ch, pts, paw, w, foot


def fore(ch: str, hx: int, hy: int, off: int = 0, lift: bool = False, ground: int = 14,
         w: int = 1, paw: int = 1, foot: str = "") -> Leg:
    """A foreleg hanging from the shoulder (hx, hy): planted ``off`` px ahead, or lifted
    and folded back under the chest."""
    if lift:
        return L(ch, (hx, hy), (hx, ground - 2), (hx - 1, ground - 1), paw=0, w=w, foot=foot)
    return L(ch, (hx, hy), (hx + off // 2, ground - 2), (hx + off, ground), paw=paw, w=w, foot=foot)


def hind(ch: str, hx: int, hy: int, off: int = 0, lift: bool = False, ground: int = 14,
         w: int = 1, paw: int = 1, foot: str = "") -> Leg:
    """A hind leg from the hip (hx, hy) with the hock bent backwards: planted ``off`` px
    ahead, or lifted with the foot drawn up."""
    if lift:
        return L(ch, (hx, hy), (hx - 1, ground - 2), (hx, ground - 1), paw=0, w=w, foot=foot)
    return L(ch, (hx, hy), (hx - 1 + off // 2, ground - 2), (hx + off, ground), paw=paw, w=w,
             foot=foot)


def _pose(w: int, h: int, body: Grid, legs: tuple[Leg, ...] = (), dx: int = 0, dy: int = 0,
          top: tuple[tuple[Grid, int, int], ...] = ()) -> Grid:
    """Legs first (the body covers their tops), then the body shifted by (dx, dy), then
    ``top`` parts, then the ink outline around everything."""
    c = Canvas(w, h)
    for ch, pts, paw, lw, foot in legs:
        for k in range(lw):
            if len(pts) == 1:
                c.set(pts[0][0] + k, pts[0][1], ch)
            for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
                c.line(x0 + k, y0, x1 + k, y1, ch)
        fx, fy = pts[-1]
        for k in range(lw, lw + paw):
            c.set(fx + k, fy, ch)
        if foot:
            for k in range(lw + paw):
                c.set(fx + k, fy, foot)
    c.blit(shift(body, dx, dy))
    for part, x, y in top:
        c.blit(part, x, y)
    return outline_grid(c.grid(), "k")


def _ol(text: str) -> Grid:
    return outline_grid(grid(text), "k")


def _shadow(g: Grid, x0: int, x1: int, y: int, rows: int = 2) -> Grid:
    """A short soft ground shadow ('S', translucent ink) under a sprite, painted only on
    transparent pixels: ``rows`` rows from ``y`` down, spanning x0..x1 (ends rounded)."""
    out = [list(r) for r in g]
    for k in range(rows):
        inset = (rows - 1 - k) if k < rows - 1 else 0
        yy = y + k
        if not 0 <= yy < len(g):
            continue
        for x in range(x0 + inset + (k == rows - 1), x1 - inset - (k == rows - 1) + 1):
            if 0 <= x < len(g[0]) and out[yy][x] == ".":
                out[yy][x] = "S"
    return tuple("".join(r) for r in out)


def _fallen(body: Grid, legs: tuple[Leg, ...], x0: int, x1: int) -> Grid:
    """A dead beast on its side: legs stiff out toward the viewer, a soft shadow beneath."""
    w, h = len(body[0]), len(body)
    return _shadow(_pose(w, h, body, legs), x0, x1, h - 2)


def _reg(name: str, frames, legend: dict, fps: float = 0.0, note: str = "") -> None:
    register(f"az.creature.{name}", art(*frames, legend={"S": "ink:60", **legend}, fps=fps, note=note))


