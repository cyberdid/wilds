def _dog_legs(off: tuple[int, int, int, int], lift: tuple[bool, ...] = (False,) * 4,
              hy: int = 7) -> tuple[Leg, ...]:
    # short straight legs in adjacent pairs: at this size a hock or a gap only adds ink
    return (fore("2", 4, hy, off[0], lift[0], ground=10), fore("2", 8, hy, off[1], lift[1], ground=10),
            fore("3", 3, hy, off[2], lift[2], ground=10), fore("3", 7, hy, off[3], lift[3], ground=10))


