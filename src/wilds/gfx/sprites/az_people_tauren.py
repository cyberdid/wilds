def _sleeved(p: Part) -> Part:
    """Upper arm (every row above the bracer) in sleeve slots 7 8 9, which default to fur
    and take the garment colours in outfits with sleeves or armoured shoulders."""
    cut = next((i for i, r in enumerate(p.rows) if "a" in r), 0)
    sw = {"q": "7", "s": "8", "S": "9"}
    rows = tuple("".join(sw.get(c, c) for c in r) if i < cut else r for i, r in enumerate(p.rows))
    return Part(rows, p.x, p.y)


