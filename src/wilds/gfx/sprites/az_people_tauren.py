@dataclass(frozen=True)
class Look:
    """What a tauren wears. ``skirt`` hangs from the hips and does not breathe;
    ``wear`` sits on the torso; ``gear`` on the head; ``back`` is slung behind;
    ``far`` is held upright in the far hand; ``over`` covers the near arm;
    ``paint`` goes on after the outline."""

    skirt: tuple[str, ...] = ()
    wear: tuple[str, ...] = ()
    gear: tuple[str, ...] = ()
    back: tuple[str, ...] = ()
    far: tuple[str, ...] = ()
    over: tuple[str, ...] = ()
    paint: tuple[str, ...] = ()
    weapon: str = ""                # attack style: axe, hammer, club, halberd, bow, cast
    hunch: int = 0                  # elders carry the head a pixel lower


def figure(rig: Rig, look: Look, legs: str = "legs.stand", arm: str = "arm.down", *,
           dx: int = 0, dy: int = 0, mouth: bool = False, blink: bool = False,
           weapon: Part | None = None, glow: Part | None = None, armed: bool = False) -> Grid:
    """One frame: legs and skirt stay put, the rest moves by (dx, dy). ``armed``
    hides the slung / far-hand weapon while it is being swung."""
    up = lambda n: rig[n].at(dx, dy)  # noqa: E731
    hy = dy + look.hunch
    parts = [up(n) for n in look.far if not (armed and look.weapon == "halberd")]
    parts += [rig[legs], up("torso")]
    parts += [up(n) for n in look.wear]
    parts += [up(n) for n in look.back if not armed]
    parts += [rig[n] for n in look.skirt]
    parts += [rig["head"].at(dx, hy)] + [rig[n].at(dx, hy) for n in look.gear]
    if mouth:
        parts.append(dot(*rig.mouth, "o").at(dx, hy))
    if weapon is not None:
        parts.append(weapon.at(dx, dy))
    parts += [up(arm)] + [up(n) for n in look.over]
    post = [rig[n].at(dx, hy) for n in look.paint]
    if glow is not None:
        post.append(glow.at(dx, dy))
    g = compose(parts, post)
    return swap(g, {"e": "s"}) if blink else g


WALK = (("legs.w0", "arm.back", 1), ("legs.w1", "arm.down", 0),
        ("legs.w2", "arm.fwd", 1), ("legs.w3", "arm.down", 0))


def idle_frames(rig: Rig, look: Look) -> list[Grid]:
    return [figure(rig, look), figure(rig, look, dy=1)]


def walk_frames(rig: Rig, look: Look) -> list[Grid]:
    return [figure(rig, look, legs, arm, dy=dy) for legs, arm, dy in WALK]


def talk_frames(rig: Rig, look: Look) -> list[Grid]:
    return [figure(rig, look, arm="arm.talk0"), figure(rig, look, arm="arm.talk1", mouth=True)]


def attack_frames(rig: Rig, look: Look) -> list[Grid]:
    style = look.weapon
    if style == "cast":
        arms = ("atk.raise", "atk.cast", "atk.cast")
        return [figure(rig, look, arm=a, glow=rig.glow(i), dx=i // 2) for i, a in enumerate(arms)]
    if style == "bow":
        out = [figure(rig, look, arm="atk.cast", weapon=rig.weapon("bow", i), armed=True) for i in range(3)]
        return out
    arms = ("atk.raise", "atk.fwd", "atk.strike")
    return [figure(rig, look, arm=a, weapon=rig.weapon(style, i), armed=True, dx=i // 2, dy=i // 2)
            for i, a in enumerate(arms)]


def hurt_frame(rig: Rig, look: Look) -> Grid:
    return figure(rig, look, "legs.hurt", "arm.hurt", dx=-1, dy=1)


