class Rig:
    def __init__(self, name: str, parts: dict[str, Part], mouth: tuple[int, int],
                 base: "Rig | None" = None, drop: int = 0) -> None:
        self.name, self.own, self.mouth, self.base, self.drop = name, parts, mouth, base, drop

    def __getitem__(self, name: str) -> Part:
        if name in self.own:
            return self.own[name]
        if self.base is None:
            raise KeyError(f"{self.name} rig has no part {name!r}")
        p = self.base[name]
        if name.startswith(_FEMALE_STATIC):
            return p
        p = p.at(0, self.drop)
        if name in _FEMALE_FITTED:
            p = masked(p, self["torso"])
        return p

    def weapon(self, style: str, i: int) -> Part:
        # the bow's belly would touch the canvas edge: keep it inside the outline margin
        return WEAPONS[style][i].at(-1 if style == "bow" else 0, self.drop)

    def glow(self, i: int) -> Part:
        return CAST_GLOW[i].at(0, self.drop)


