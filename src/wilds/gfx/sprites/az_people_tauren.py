# --- parts and composition ------------------------------------------------------------


@dataclass(frozen=True)
class Part:
    """A fill-only piece of a figure: full-width rows placed at (x, y)."""

    rows: Grid
    x: int = 0
    y: int = 0

    def at(self, dx: int = 0, dy: int = 0) -> "Part":
        return Part(self.rows, self.x + dx, self.y + dy)


def part(y: int, text: str, x: int = 0) -> Part:
    return Part(grid(text), x, y)


def dot(x: int, y: int, ch: str) -> Part:
    return Part((ch,), x, y)


def compose(parts, post=(), size=(W, H)) -> Grid:
    """Layer parts in order, outline the silhouette, then add unoutlined extras."""
    out = blank(*size)
    for p in parts:
        out = overlay(out, p.rows, p.x, p.y)
    out = outline_grid(out, "k")
    for p in post:
        out = overlay(out, p.rows, p.x, p.y)
    return out


def masked(p: Part, shape: Part) -> Part:
    """``p`` kept only where ``shape`` is opaque (a male garment fitted to a female torso)."""
    base = overlay(blank(W, H), p.rows, p.x, p.y)
    mask = overlay(blank(W, H), shape.rows, shape.x, shape.y)
    rows = tuple("".join(c if m != "." else "." for c, m in zip(r, mr)) for r, mr in zip(base, mask))
    return Part(rows)


