"""Azeroth / Mulgore art: people tauren. Must satisfy
``wilds.azeroth.manifest.required()["people_tauren"]`` (see docs/azeroth/mulgore-art-manifest.md).

Tauren are tall (16x24 at real scale: 1 yard = 8 px), face RIGHT in a 3/4 side
view and stand with their hooves on the bottom row.

How the art is built
--------------------
Like ``city_people`` each body (male, female) is a *rig* of fill-only parts
written in *slot* characters; a frame is a list of parts layered in order and
the 1px ``ink`` outline is added after composing, so any gear that changes the
silhouette (a totem staff, antlers, an axe) gets a clean outline for free.
An outfit is a :class:`Look` (which garment / gear parts) plus a slot ->
palette mapping, so eleven outfits share one male and one female base.

Slot characters::

    q s S   fur light / mid / shadow        d D   hands (fur) mid / shadow
    j h H   hair / mane light / mid / dark   n N   horn light / dark
    u U     muzzle / nose + nostril          e o   eye, open mouth
    y t T   top garment light / mid / shadow p P   kilt / skirt mid / shadow
    a A     accent (belt, bracer, trim)      x X   second garment (apron, shawl, quiver)
    c C     metal light / dark               g G   wood light / dark
    r       war paint / red feather tip      f F   feather light / dark
    l L     leaf light / dark                b     bead (turquoise)
    z Z     spell glow bright / dim          v V   hoof light / dark
    m       string (bow)                     k K w ink, ink2, white (always available)
"""

