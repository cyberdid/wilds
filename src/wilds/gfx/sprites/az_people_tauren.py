def portrait_grid(p: Portrait) -> Grid:
    parts = [PORTRAIT[p.body]] + [PORTRAIT[n] for n in p.over]
    g = compose(parts, [PORTRAIT[n] for n in p.post], size=(PW, PW))
    return swap(g, {"w": "z", "e": "z"}) if p.glow else g


def _register_portraits() -> None:
    for npc, p in PORTRAITS.items():
        register(f"az.portrait.{npc}", art(portrait_grid(p), legend=p.legend, note=p.note))


