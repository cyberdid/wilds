    # thruster nozzle and flame under the hull
    c.set(7 + lean, 10 + oy, "T"); c.set(8 + lean, 10 + oy, "T")
    if flame:
        c.set(7 + lean, 11 + oy, "f" if flame == 1 else "F")
        c.set(8 + lean, 11 + oy, "F" if flame == 1 else "f")
    return outline_grid(c.grid(), "k")


