# brute: a hulking knuckle-walker. Bone plates on the hump, forward horns, tiny
# ember eyes (neon_orange). Built from shaded forms so every frame shares one body.

BRUTE = {"0": "brute0", "1": "brute1", "2": "brute2", "3": "brute3", "4": "brute4",
         "a": "bone4", "b": "bone3", "B": "bone2", "d": "bone1", "e": "neon_orange", "m": "red1"}


def _ellipse(cx: float, cy: float, rx: float, ry: float, w: int = 24, h: int = 24) -> set:
    return {(x, y) for y in range(h) for x in range(w)
            if ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2 <= 1.0}


def _box(x0: int, y0: int, x1: int, y1: int) -> set:
    return {(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)}


def _paint(c: Canvas, pts: set, light: str, main: str, dark: str) -> None:
    """One form lit from the top-left: top/left rim light, bottom rim dark."""
    for (x, y) in pts:
        if (x, y - 1) not in pts or (x - 1, y) not in pts and (x, y - 1) not in pts:
            ch = light
        elif (x, y + 1) not in pts or (x + 1, y + 1) not in pts:
            ch = dark
        else:
            ch = main
        c.set(x, y, ch)


def _brute(dx: int = 0, dy: int = 0, front: int = 0, hind: int = 0, head: tuple = (0, 0),
           arm_up: bool = False, flash: bool = False) -> Grid:
    """dx/dy move the upper body; front/hind (-1..1) swing the near limbs;
    head offsets the skull; arm_up raises the near fist for a swipe."""
    c = Canvas(24, 24)
    ox, oy = dx, dy
    # far limbs (darkest), behind the body
    _paint(c, _box(9 - hind, 17 + oy, 10 - hind, 21), "1", "1", "0")
    _paint(c, _box(13 + front, 17 + oy, 14 + front, 21), "1", "1", "0")
    # body mass + hump
    body = _ellipse(11.5 + ox, 13.0 + oy, 8.2, 5.2) | _ellipse(12.5 + ox, 10.5 + oy, 6.0, 4.2)
    _paint(c, body, "3", "2", "1")
    for (x, y) in body:  # belly shadow band
        if y >= 16 + oy and c.get(x, y) == "2":
            c.set(x, y, "1")
    # hind leg (near): thick thigh into a short shin
    thigh = _ellipse(6.0 + ox - hind * 0.5, 15.5 + oy, 2.6, 2.6)
    shin = _box(5 - hind, 17 + oy, 7 - hind, 21)
    _paint(c, thigh | shin, "3", "2", "1")
    # head: low, heavy brow, horns forward
    hx, hy = 19.2 + ox + head[0], 14.8 + oy + head[1]
    skull = _ellipse(hx, hy, 3.1, 2.7)
    _paint(c, skull, "3", "2", "1")
    ix, iy = int(hx), int(hy)
    c.set(ix + 1, iy - 1, "e")                      # ember eye under the brow
    c.set(ix, iy - 2, "4"); c.set(ix + 1, iy - 2, "4")
    c.set(ix + 2, iy + 1, "m"); c.set(ix + 1, iy + 1, "m")   # mouth line
    for (x, y) in ((ix + 1, iy - 3), (ix + 2, iy - 4), (ix + 2, iy - 5), (ix + 3, iy - 6)):
        c.set(x, y, "b")                            # near horn
    c.set(ix + 3, iy - 5, "a"); c.set(ix + 3, iy - 4, "B")
    for (x, y) in ((ix - 1, iy - 3), (ix - 1, iy - 4), (ix, iy - 5)):
        c.set(x, y, "B")                            # far horn
    # bone plates along the hump
    for (px, py, w) in ((6, 8, 2), (9, 6, 3), (13, 6, 3), (16, 8, 2)):
        for k in range(w):
            c.set(px + ox + k, py + oy, "a" if k == 0 else "b")
            c.set(px + ox + k, py + oy + 1, "B" if k == 0 else "d")
        c.set(px + ox + w // 2, py + oy - 1, "b")
    # near arm: a massive forelimb down to the knuckles (or raised for a swipe)
    if arm_up:
        arm = _box(15 + ox, 7 + oy, 17 + ox, 12 + oy) | _ellipse(17.5 + ox, 6.5 + oy, 2.0, 1.8)
    else:
        arm = (_box(15 + ox + front, 13 + oy, 17 + ox + front, 20)
               | _box(15 + front, 19, 18 + front, 21))
    _paint(c, arm, "4", "3", "1")
    g = shift(c.grid(), 0, 1)  # soles on row 22, outline on row 23 = the anchor row
    if flash:
        g = tuple(row.replace("2", "3") for row in g)
    return outline_grid(g, "k")


