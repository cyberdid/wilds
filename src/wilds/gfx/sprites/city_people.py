def _group(name: str) -> str:
    if name.startswith("legs.") or name in _SKIRTS:
        return "legs"
    if name == "head" or name.startswith("hair.") or name in _HEAD_GEAR:
        return "head"
    return "body" if name in _BODY_WEAR else "arm"


def derive(race: str, size: tuple[int, int], eye: tuple[int, int], mouth: tuple[int, int],
           offsets: dict[str, tuple[int, int]], parts: dict[str, Part],
           over: tuple[str, ...] = ()) -> Rig:
    """A rig whose unlisted parts are the human's, moved by their group's offset."""
    out = {}
    for name, p in HUMAN.parts.items():
        off = offsets.get(_group(name))
        if off is not None:
            out[name] = p.at(*off)
    out.update(parts)
    missing = sorted(set(HUMAN.parts) - set(out))
    if missing:
        raise ValueError(f"{race} rig lacks {missing}")
    return Rig(race, size, eye, mouth, out, over)


def _coat(y: int, text: str) -> dict[str, Part]:
    p = part(y, text)
    return {"fixer.coat": p, "doc.coat": p}


