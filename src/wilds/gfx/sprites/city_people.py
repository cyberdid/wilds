def _t(y: int, arm: str, *props: tuple[int, int, str]) -> Part:
    """A troll arm pose (rows from ``y``) with prop pixels (x, y, char) laid over it."""
    g = grid(arm)
    for x, py, ch in props:
        row = g[py - y]
        g = g[:py - y] + (row[:x] + ch + row[x + 1:],) + g[py - y + 1:]
    return Part(g, 0, y)


