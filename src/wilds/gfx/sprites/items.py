GOLD = {"chrome3": "gold3", "chrome2": "gold2", "chrome1": "gold1", "chrome0": "gold0"}


def _alpha(key: str, base: str, legend: dict, note: str) -> None:
    g = grid(base)
    gold = recolor(art(g, g, legend=legend), GOLD)
    register(f"cp.item.{key}_alpha", art(*gold.frames, legend=dict(gold.legend), fps=3, note=note))


