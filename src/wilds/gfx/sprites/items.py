def _steam(frames: int = 4) -> list[Grid]:
    """Two thin wisps rising off the food, one S-curve step per frame (loops)."""
    wiggle = (0, 1, 1, 0)
    out = []
    for t in range(frames):
        rows = [["."] * 16 for _ in range(6)]
        for x0, top, bottom in ((5, 1, 5), (9, 0, 4)):
            for y in range(top, bottom + 1):
                rows[y][x0 + wiggle[(y + t) % 4]] = "s" if y > (top + bottom) // 2 else "S"
        out.append(pad(tuple("".join(r) for r in rows), bottom=10))
    return out


